function buildPartPayload(partSpec) {
  return {
    name: partSpec.name,
    brand: partSpec.brand,
    category: partSpec.category,
    subCategory: partSpec.subCategory || '',
    partNumber: partSpec.partNumber || '',
    quantity: partSpec.quantity ?? 1,
    specs: partSpec.specs,
    structuredSpecs: partSpec.structuredSpecs || [],
    manufacturerUrl: partSpec.manufacturerUrl || '',
    imageUrl: partSpec.imageUrl || '',
    catalogKey: partSpec.catalogKey || '',
    serialNumber: '',
    status: 'in_use',
    bikeId: SPECIALIZED_STATUS_160_ID,
    notes: '',
  };
}

export function seedInitialData(db) {
  if (db.getMeta('initial_seed_applied') === '1') {
    return;
  }

  db.runInTransaction(() => {
    if (db.getMeta('initial_seed_applied') === '1') {
      return;
    }

    if (db.listBikes().length === 0) {
      db.createBike(SPECIALIZED_STATUS_160_BIKE, SPECIALIZED_STATUS_160_ID);
      for (const part of SPECIALIZED_STATUS_160_PARTS) {
        db.createPart(buildPartPayload(part));
      }
      db.setMeta('catalog_version', CURRENT_CATALOG_VERSION);
      db.recordUpdateHistory({
        id: `catalog-v${CURRENT_CATALOG_VERSION}`,
        updateType: 'catalog',
        version: CURRENT_CATALOG_VERSION,
        description:
          'Initialer Hersteller-Katalog für Specialized Status 160 (60 Komponenten inkl. Bildern & technischen Daten).',
        details: `${SPECIALIZED_STATUS_160_PARTS.length} Komponenten angelegt.`,
      });
    }

    db.setMeta('initial_seed_applied', '1');
  });
}

export function applyCatalogUpdates(db, { force = false } = {}) {
  const currentCatalog = db.getMeta('catalog_version') || '1.0.0';
  if (!force && currentCatalog === CURRENT_CATALOG_VERSION) {
    return {
      applied: false,
      version: CURRENT_CATALOG_VERSION,
      bikeUpdated: false,
      partsAdded: 0,
      partsUpdated: 0,
    };
  }

  return db.runInTransaction(() => {
    let bikeUpdated = false;
    let partsAdded = 0;
    let partsUpdated = 0;

    const existingBike = db.getBike(SPECIALIZED_STATUS_160_ID);
    if (existingBike) {
      const nextBikeImage = existingBike.imageUrl || SPECIALIZED_STATUS_160_BIKE.imageUrl;
      const nextManufacturerUrl =
        existingBike.manufacturerUrl || SPECIALIZED_STATUS_160_BIKE.manufacturerUrl;
      if (
        nextBikeImage !== existingBike.imageUrl ||
        nextManufacturerUrl !== existingBike.manufacturerUrl
      ) {
        db.updateBike(SPECIALIZED_STATUS_160_ID, {
          name: existingBike.name,
          brand: existingBike.brand,
          model: existingBike.model,
          modelYear: existingBike.modelYear,
          category: existingBike.category,
          frameSize: existingBike.frameSize,
          wheelSize: existingBike.wheelSize,
          color: existingBike.color,
          serialNumber: existingBike.serialNumber,
          imageUrl: nextBikeImage,
          manufacturerUrl: nextManufacturerUrl,
          notes: existingBike.notes || SPECIALIZED_STATUS_160_BIKE.notes,
        });
        bikeUpdated = true;
      }

      const allParts = db.listParts();
      const existingBikeParts = allParts.filter(
        (part) => part.bikeId === SPECIALIZED_STATUS_160_ID,
      );
      const existingCatalogKeysElsewhere = new Set(
        allParts
          .filter((part) => part.bikeId !== SPECIALIZED_STATUS_160_ID && part.catalogKey)
          .map((part) => part.catalogKey),
      );
      const matchedPartIds = new Set();

      for (const spec of SPECIALIZED_STATUS_160_PARTS) {
        const legacySet = new Set(
          [spec.name, ...(spec.legacyNames || [])].map((item) => item.toLowerCase()),
        );
        const match = existingBikeParts.find(
          (p) =>
            !matchedPartIds.has(p.id) &&
            ((p.catalogKey && p.catalogKey === spec.catalogKey) ||
              legacySet.has(p.name.toLowerCase())),
        );

        if (match) {
          matchedPartIds.add(match.id);
          db.updatePart(match.id, {
            name: spec.name,
            brand: spec.brand,
            category: spec.category,
            subCategory: spec.subCategory || '',
            partNumber: match.partNumber || spec.partNumber || '',
            quantity: spec.quantity ?? 1,
            specs: spec.specs,
            structuredSpecs: spec.structuredSpecs || [],
            manufacturerUrl: match.manufacturerUrl || spec.manufacturerUrl || '',
            imageUrl: match.imageUrl || spec.imageUrl || '',
            catalogKey: spec.catalogKey,
            serialNumber: match.serialNumber,
            status: match.status,
            bikeId: match.bikeId,
            notes: match.notes,
          });
          partsUpdated += 1;
        } else if (!existingCatalogKeysElsewhere.has(spec.catalogKey)) {
          db.createPart(buildPartPayload(spec));
          partsAdded += 1;
        }
      }
    }

    db.setMeta('catalog_version', CURRENT_CATALOG_VERSION);
    db.recordUpdateHistory({
      id: `catalog-v${CURRENT_CATALOG_VERSION}`,
      updateType: 'catalog',
      version: CURRENT_CATALOG_VERSION,
      description:
        'Specialized Status 160 Katalog-Update: Vollständige 60-Teile-Erfassung, Produktbilder & Hersteller-Spezifikationen.',
      details: `${partsAdded} neue Komponenten ergänzt, ${partsUpdated} bestehende Komponenten aktualisiert.`,
    });

    return {
      applied: true,
      version: CURRENT_CATALOG_VERSION,
      bikeUpdated,
      partsAdded,
      partsUpdated,
    };
  });
}
